import type { Plugin } from 'vite'

/**
 * Emits Cloudflare Pages `_headers` for the build: CSP scoped to the API
 * origin, caching rules, framing/sniffing protection. With
 * DF_REQUIRE_HTTPS_API=1 (production builds) a non-HTTPS API URL fails the
 * build, so mixed content cannot ship.
 */
export function cloudflarePagesHeaders(apiUrl: string): Plugin {
  return {
    name: 'df-cloudflare-pages-headers',
    apply: 'build',
    buildStart() {
      const url = new URL(apiUrl)
      if (process.env.DF_REQUIRE_HTTPS_API === '1' && url.protocol !== 'https:') {
        this.error(`VITE_SUPABASE_URL must be https:// for production builds (got ${url.origin})`)
      }
    },
    generateBundle() {
      const api = new URL(apiUrl).origin
      const https = api.startsWith('https://')
      const csp = [
        "default-src 'self'",
        "script-src 'self'",
        // React style attributes (timeline positions) need inline styles; scripts stay strict.
        "style-src 'self' 'unsafe-inline'",
        "img-src 'self' data: blob:",
        "font-src 'self'",
        `connect-src 'self' ${api}`,
        "manifest-src 'self'",
        "worker-src 'self'",
        "frame-ancestors 'none'",
        "base-uri 'self'",
        "form-action 'self'",
        "object-src 'none'",
        ...(https ? ['upgrade-insecure-requests'] : []),
      ].join('; ')
      const source = `# Generated by apps/web/build/cloudflare-pages.ts — do not edit.
# SPA fallback is automatic on Cloudflare Pages (no 404.html at the root).
/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()
  X-Frame-Options: DENY
${https ? '  Strict-Transport-Security: max-age=31536000; includeSubDomains\n' : ''}
/assets/*
  Cache-Control: public, max-age=31536000, immutable

/index.html
  Cache-Control: no-cache

/sw.js
  Cache-Control: no-cache

/workbox-*.js
  Cache-Control: no-cache

/tenants/:slug/manifest.webmanifest
  Cache-Control: public, max-age=300

/tenants/:slug/icons/*
  Cache-Control: public, max-age=86400
`
      this.emitFile({ type: 'asset', fileName: '_headers', source })
    },
  }
}
